#!/usr/bin/env node

/**
 * Write the host-root `.flowconfig` and `flow/` stubs from shared templates.
 *
 * Flow has no `extends`. The live file must stay at the host root so
 * PROJECT_ROOT is the consumer, not this package.
 *
 * Run from the consuming project root:
 *   node packages/global-packages/packages/dev-tools/js/flow/write-flowconfig.js --project=<id>
 */

const fs = require( 'fs' );
const path = require( 'path' );

const PROJECT_IDS = [
	'blockera',
	'blockera-pro',
	'blockera-one',
	'blockera-site-toolkit',
];

const SECTION_ORDER = [
	'ignore',
	'include',
	'libs',
	'lints',
	'options',
	'strict',
];

const GENERATED_HEADER = [
	'# Generated by @blockera/dev-tools. Do not edit this file.',
	'# Edit packages/global-packages/packages/dev-tools/flow/ then run:',
	'#   npm run project:bootstrap',
	'',
].join( '\n' );

const FLOW_DIR = path.join( __dirname, '..', '..', 'flow' );
const FLOW_STUB_FILES = [
	'TypeScriptModule.js.flow',
	'WebpackAsset.js.flow',
];

function parseProjectId( argv ) {
	const prefix = '--project=';
	const arg = argv.find( ( item ) => item.startsWith( prefix ) );

	if ( ! arg ) {
		throw new Error(
			`missing --project=<id> (one of: ${ PROJECT_IDS.join( ', ' ) })`
		);
	}

	const id = arg.slice( prefix.length ).trim();

	if ( ! PROJECT_IDS.includes( id ) ) {
		throw new Error(
			`unknown --project=${ id } (one of: ${ PROJECT_IDS.join( ', ' ) })`
		);
	}

	return id;
}

function parseFlowconfig( text ) {
	const sections = {};
	let current = null;

	for ( const rawLine of String( text ).replace( /\r\n/g, '\n' ).split( '\n' ) ) {
		const heading = rawLine.match( /^\[([^\]]+)\]\s*$/ );

		if ( heading ) {
			current = heading[ 1 ];

			if ( ! sections[ current ] ) {
				sections[ current ] = [];
			}

			continue;
		}

		if ( ! current ) {
			continue;
		}

		sections[ current ].push( rawLine );
	}

	return sections;
}

function trimSectionLines( lines ) {
	const next = [ ...lines ];

	while ( next.length && next[ 0 ].trim() === '' ) {
		next.shift();
	}

	while ( next.length && next[ next.length - 1 ].trim() === '' ) {
		next.pop();
	}

	return next;
}

function mergeSections( base, overlay ) {
	const merged = {};

	for ( const name of new Set( [
		...Object.keys( base ),
		...Object.keys( overlay ),
	] ) ) {
		merged[ name ] = [
			...trimSectionLines( base[ name ] || [] ),
			...trimSectionLines( overlay[ name ] || [] ),
		];
	}

	return merged;
}

function serializeFlowconfig( sections ) {
	const names = [
		...SECTION_ORDER.filter( ( name ) => name in sections ),
		...Object.keys( sections ).filter(
			( name ) => ! SECTION_ORDER.includes( name )
		),
	];

	const blocks = names.map( ( name ) => {
		const body = trimSectionLines( sections[ name ] || [] );

		if ( ! body.length ) {
			return `[${ name }]\n`;
		}

		return `[${ name }]\n${ body.join( '\n' ) }\n`;
	} );

	return `${ GENERATED_HEADER }${ blocks.join( '\n' ) }`;
}

function readTemplate( filePath ) {
	if ( ! fs.existsSync( filePath ) ) {
		return '';
	}

	return fs.readFileSync( filePath, 'utf8' );
}

function writeFlowconfig( { root, projectId } ) {
	if ( ! PROJECT_IDS.includes( projectId ) ) {
		throw new Error(
			`unknown --project=${ projectId } (one of: ${ PROJECT_IDS.join(
				', '
			) })`
		);
	}

	const basePath = path.join( FLOW_DIR, 'flowconfig.base' );

	if ( ! fs.existsSync( basePath ) ) {
		throw new Error( `missing Flow template: ${ basePath }` );
	}

	const overlayPath = path.join( FLOW_DIR, 'overlays', projectId );
	const sections = mergeSections(
		parseFlowconfig( readTemplate( basePath ) ),
		parseFlowconfig( readTemplate( overlayPath ) )
	);
	const dest = path.join( root, '.flowconfig' );

	fs.writeFileSync( dest, serializeFlowconfig( sections ) );

	return dest;
}

function writeFlowStubs( { root } ) {
	const destDir = path.join( root, 'flow' );

	fs.mkdirSync( destDir, { recursive: true } );

	const written = FLOW_STUB_FILES.map( ( fileName ) => {
		const src = path.join( FLOW_DIR, fileName );

		if ( ! fs.existsSync( src ) ) {
			throw new Error( `missing Flow stub: ${ src }` );
		}

		const dest = path.join( destDir, fileName );

		fs.copyFileSync( src, dest );

		return dest;
	} );

	return written;
}

function main() {
	try {
		const projectId = parseProjectId( process.argv.slice( 2 ) );
		const root = process.cwd();
		const dest = writeFlowconfig( {
			root,
			projectId,
		} );
		const stubs = writeFlowStubs( { root } );

		// @debug-ignore — CLI stdout for Flow config writer
		console.log( `wrote ${ dest }` );
		stubs.forEach( ( stub ) => {
			// @debug-ignore — CLI stdout for Flow config writer
			console.log( `wrote ${ stub }` );
		} );
	} catch ( error ) {
		// @debug-ignore — CLI stderr for Flow config writer
		console.error( error.message || error );
		process.exit( 1 );
	}
}

if ( require.main === module ) {
	main();
}

module.exports = {
	PROJECT_IDS,
	writeFlowconfig,
	writeFlowStubs,
};
